// Prepare/Emit.ts - the writing half of the generator.
//
// `Scripts/Prepare.ts` resolves the module; this file turns the manifest rows
// into files. Three laws live here, and none of them are negotiable:
//
// 1. FACTS FAN IN. Six primaries feed one version file, so rows that share a
//    `Destination` are merged into one object, each row's fragment under its
//    own `Fact` key. One destination is written once per run.
// 2. EVERY FILE NAMES ITS SOURCE. A JSON destination carries a `_Generated`
//    key listing every `Module/Aphrodite/...` path it was built from; a text
//    destination carries the same facts as a comment in its own syntax.
// 3. NOTHING IS DELETED. A file under `Source/Generated/` that this run did
//    not write is reported as an orphan for a human to decide on. A generator
//    that removes files is a generator that can reduce the site, and this one
//    may not.

import { existsSync, mkdirSync, readFileSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve } from "node:path";

import type { Row } from "./Manifest.ts";
import { Comment, Parse, Provenance } from "./Transform.ts";
import GenerateDocs from "../Docs/Generate.ts";

/** What one run produced, for the summary line. */
export interface Result {
	/** The destinations written, relative to the Site root. */
	Written: string[];

	/** The declared-but-held rows with what Prepare found at the source. */
	Held: { Source: string; Destination: string; Detail: string }[];

	/** The files under `Source/Generated/` this run did not write. */
	Orphans: string[];

	/** The docs tree's own report: what it wrote, what it could not reach. */
	Docs: {
		Written: number;
		Gaps: string[];
		Orphans: string[];
		Stale: string[];
		Hermetic: boolean;
	};
}

/** Every file under a directory, optionally filtered by extension. */
function Walk(Directory: string, Extension: string | null): string[] {
	const Files: string[] = [];

	for (const Entry of readdirSync(Directory)) {
		const Path = join(Directory, Entry);

		switch (true) {
			case statSync(Path).isDirectory():
				Files.push(...Walk(Path, Extension));
				break;
			case Extension === null || Entry.endsWith(Extension):
				Files.push(Path);
				break;
		}
	}

	return Files;
}

/** A destination the row declares as a whole tree. */
function IsTree(Source: string): boolean {
	return Source.endsWith("/**");
}

/** The path a tree row points at, with the glob suffix removed. */
function Tree(Source: string): string {
	return Source.replace(/\/\*\*$/, "");
}

/** Write one destination, creating its directory. */
function Write(Site: string, Destination: string, Body: string): void {
	const Target = resolve(Site, Destination);

	mkdirSync(dirname(Target), { recursive: true });
	writeFileSync(Target, Body, "utf8");
}

/** Read a source as LF text, so a CRLF checkout generates the same bytes as an LF one. */
function Read(Path: string): string {
	return readFileSync(Path, "utf8").replace(/\r\n/g, "\n");
}

/**
 * The generated area's own marker: what lands in it, what is held, and the law
 * a reader needs before editing anything here. Derived from the manifest, so
 * it cannot describe a table that no longer exists.
 */
export function Marker(Site: string, Rows: Row[]): string {
	const Destination = "Source/Generated/GENERATED.md";
	const Emitted = Rows.filter((Row) => Row.Stage === "Emit");
	const Held = Rows.filter((Row) => Row.Stage === "Hold");

	const Body = [
		"<!-- Generated by Scripts/Prepare.ts from the manifest in Scripts/Prepare/Manifest.ts. Do not edit. -->",
		"",
		"# The generated area",
		"",
		"Everything under `Source/Generated/` is written by `Scripts/Prepare.ts` from",
		"the `Module/Aphrodite` submodule, on every build. Nothing here is edited by",
		"hand: a change made in this directory is overwritten by the next run.",
		"",
		"## What lands here",
		"",
		...Emitted.map(
			(Row) =>
				`- \`${Row.Destination}\` <- \`Module/Aphrodite/${Row.Source}\` (${Row.Transform}) - ${Row.Consumer}`,
		),
		"",
		"## What is declared and held",
		"",
		"These rows are verified on every run and written by the extraction card that",
		"owns them, not by this one:",
		"",
		...Held.map(
			(Row) => `- \`${Row.Source}\` -> \`${Row.Destination}\` (${Row.Transform}) - ${Row.Note ?? ""}`,
		),
		"",
		"## How a fact changes",
		"",
		"Never in this directory. Edit `~/Developer/Application/PlayForm/Aphrodite`,",
		"port to `Aphrodite-Release`, commit, push, verify the remote tip, advance the",
		"`Module/Aphrodite` pin in this repository, then rebuild. The eight steps are",
		"in the site README.",
		"",
		"## The additive law",
		"",
		"A source file with no manifest row is a gap in the manifest, not a licence to",
		"skip content. A page with no module counterpart survives generation: it is",
		"pushed up into `PlayForm/Aphrodite` so it gains a source, or the manifest",
		"declares it site-only with a reason. Generation is the union of the best",
		"content at both ends, never the intersection.",
		"",
	].join("\n");

	Write(Site, Destination, Body);

	return Destination;
}

/**
 * Run the manifest: write every `Emit` row, verify every `Hold` row, and report
 * what this run did not touch. Throws on a source a `Fail` row cannot find,
 * because a build that silently loses a fact is worse than one that stops.
 */
export function Emit(Module: string, Site: string, Rows: Row[]): Result {
	const Written: string[] = [];
	const Held: Result["Held"] = [];
	const Groups = new Map<string, Row[]>();
	const DocRows: Row[] = [];

	for (const Row of Rows) {
		switch (Row.Stage) {
			case "Hold": {
				const Path = join(Module, Tree(Row.Source));
				const Detail = !existsSync(Path)
					? "SOURCE ABSENT"
					: IsTree(Row.Source)
						? `${Walk(Path, ".md").length} markdown file(s)`
						: "source present";

				Held.push({ Source: Row.Source, Destination: Row.Destination, Detail });

				break;
			}
			case "Emit": {
				switch (Row.Transform) {
					case "Doc":
						// The docs are a BATCH, not a per-row write: every page's
						// relative links resolve against the whole route map, so
						// the table is written once after the loop.
						DocRows.push(Row);

						break;
					case "Mermaid":
						throw new Error(
							`[Prepare] ${Row.Source} is a "${Row.Transform}" row marked Emit, and this generator does not implement that transform. Implement it in Scripts/Prepare/Transform.ts, or declare the row Stage: "Hold" until its extraction card lands.`,
						);
					case "Facts": {
						const Group = Groups.get(Row.Destination) ?? [];

						Group.push(Row);
						Groups.set(Row.Destination, Group);

						break;
					}
					default: {
						const Path = join(Module, Row.Source);

						if (!existsSync(Path)) {
							if (Row.Absent === "Fail") {
								throw new Error(
									`[Prepare] ${Row.Source} is missing from ${Module}. ${Row.Note ?? ""}`.trim(),
								);
							}

							console.warn(`[Prepare] ${Row.Source} is absent; ${Row.Destination} is not written.`);

							break;
						}

						Write(Site, Row.Destination, Comment(Row.Destination, [Row]) + Read(Path));
						Written.push(Row.Destination);
					}
				}

				break;
			}
		}
	}

	// The fan-in: one object per destination, one write per destination.
	for (const [Destination, Group] of Groups) {
		const Facts: Record<string, unknown> = {};

		for (const Row of Group) {
			const Path = join(Module, Row.Source);

			if (!existsSync(Path)) {
				if (Row.Absent === "Fail") {
					throw new Error(
						`[Prepare] ${Row.Source} is missing from ${Module}. ${Row.Note ?? ""}`.trim(),
					);
				}

				console.warn(`[Prepare] ${Row.Source} is absent; ${Destination} carries no "${Row.Fact}" fragment.`);

				continue;
			}

			if (Row.Parser === undefined || Row.Fact === undefined) {
				throw new Error(
					`[Prepare] ${Row.Source} is a Facts row without a Parser and a Fact. Both are required in the manifest.`,
				);
			}

			Facts[Row.Fact] = Parse(Row.Parser, {
				Text: Read(Path),
				Source: Row.Source,
				Module,
			});
		}

		Write(
			Site,
			Destination,
			`${JSON.stringify({ _Generated: Provenance(Group), ...Facts }, null, "\t")}\n`,
		);

		Written.push(Destination);
	}

	Written.push(Marker(Site, Rows));

	// The docs batch: one route map, one pass, every page. A gap is a module doc
	// no row reaches, and it stops the build - a doc the site cannot serve is a
	// page it silently lost.
	const Docs = DocRows.length > 0
		? GenerateDocs(Module, Site)
		: { Written: [], Gaps: [], Orphans: [], Stale: [], Hermetic: true };

	if (Docs.Gaps.length > 0) {
		throw new Error(
			`[Prepare] ${Docs.Gaps.length} module doc(s) have no row in Scripts/Prepare/Docs.ts: ${Docs.Gaps.join(", ")}. Add the row (or declare the file under Internal with a reason) - a doc no row reaches is a page the site does not have.`,
		);
	}

	Written.push(...Docs.Written);

	const Known = new Set(Written.map((Destination) => resolve(Site, Destination)));
	const Area = resolve(Site, "Source", "Generated");

	const Orphans = existsSync(Area)
		? Walk(Area, null)
				.filter((Path) => !Known.has(Path))
				.map((Path) => relative(Site, Path))
		: [];

	return {
		Written,
		Held,
		Orphans,
		Docs: {
			Written: Docs.Written.length,
			Gaps: Docs.Gaps,
			Orphans: Docs.Orphans,
			Stale: Docs.Stale,
			Hermetic: Docs.Hermetic,
		},
	};
}
